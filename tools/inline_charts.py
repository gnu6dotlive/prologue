#!/usr/bin/env python3
"""Insère les graphiques de données dans les pages, en SVG, pour les rendre interactifs.

Les graphiques générés par tools/make_charts.py étaient des images (<img>). Insérés
dans la page, leurs marques (barres, points, jalons) portent une fiche au survol
ou au toucher, et leurs bascules montrent ou cachent une série (assets/charts.js).
Les identifiants internes de chaque SVG sont préfixés par le nom du graphique, pour
que deux graphiques d'une même page ne se marchent pas dessus. À l'impression, le
graphique reste tel quel.

Le script remplace aussi un graphique déjà inséré : il peut être relancé après
tools/make_charts.py.

Usage : python3 tools/inline_charts.py
"""

from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIAGRAMS = ROOT / "assets" / "diagrams"
MARK = "generated by tools/make_charts.py"


def charts() -> set[str]:
    return {p.stem for p in DIAGRAMS.glob("*.svg") if MARK in p.read_text(encoding="utf-8")}


def inline_svg(name: str, lang: str) -> str:
    path = (DIAGRAMS / "en" if lang == "en" else DIAGRAMS) / f"{name}.svg"
    s = path.read_text(encoding="utf-8").strip()
    s = s.replace(f"<!-- {MARK} -->\n", "")
    s = re.sub(r'\bid="([^"]+)"', lambda m: f'id="{name}-{m.group(1)}"', s)
    s = re.sub(r"url\(#([^)]+)\)", lambda m: f"url(#{name}-{m.group(1)})", s)
    s = s.replace('aria-labelledby="t d"', f'aria-labelledby="{name}-t {name}-d"')
    s = s.replace('width="1200" height=', 'class="chart" data-chart="' + name + '" width="1200" height=', 1)
    return f"<!-- chart:{name} -->\n      {s}\n      <!-- /chart:{name} -->"


def process(page: Path, names: set[str]) -> int:
    lang = "en" if page.parent.name == "en" else "fr"
    s = page.read_text(encoding="utf-8")
    count = 0

    def again(m):
        nonlocal count
        count += 1
        return inline_svg(m.group(1), lang)
    s = re.sub(r"<!-- chart:([\w-]+) -->.*?<!-- /chart:\1 -->", again, s, flags=re.S)

    def first(m):
        nonlocal count
        name = m.group(1)
        if name not in names:
            return m.group(0)
        count += 1
        return inline_svg(name, lang)
    s = re.sub(r'<img src="(?:\.\./)?assets/diagrams/(?:en/)?([\w-]+)\.svg"[^>]*>', first, s)

    if count:
        prefix = "../" if lang == "en" else ""
        tag = f'<script src="{prefix}assets/charts.js" defer></script>'
        if tag not in s:
            s = s.replace("</head>", tag + "\n</head>", 1)
    page.write_text(s, encoding="utf-8")
    return count


def main():
    names = charts()
    for page in sorted(list(ROOT.glob("*.html")) + list((ROOT / "en").glob("*.html"))):
        n = process(page, names)
        if n:
            print(f"{page.relative_to(ROOT)!s:20} {n} graphique{'s' if n > 1 else ''}")


if __name__ == "__main__":
    main()
