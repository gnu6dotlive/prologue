MARK = "<!-- generated by tools/make_charts.py -->"
FONT = "'Space Grotesk', sans-serif"

SHELL, WHITE, INK, SLATE, MUTED = "#F7F3ED", "#FFFFFF", "#111418", "#667085", "#A1A6AD"
HAIR, QUIET = "#D7DADF", "#E6E8EB"
ORANGE, ORANGE7, ORANGE1 = "#FF6A00", "#C95400", "#FFE5D2"
GREEN, GREEN7, GREEN1 = "#5F7F52", "#455F3D", "#E8EFE5"
BLUE, BLUE7, BLUE1 = "#4169E1", "#2446A8", "#E8EDFF"

LANG = "fr"


def L(fr: str, en: str) -> str:
    return en if LANG == "en" else fr


def n(x: float, d: int = 0) -> str:
    """Nombre dans la typographie de la langue."""
    s = f"{x:,.{d}f}"
    if LANG == "en":
        return s
    return s.replace(",", " ").replace(".", ",").replace(" ", " ")


def esc(s: str) -> str:
    return html.escape(s, quote=False)


def t(x, y, s, size=13, weight=400, fill=INK, anchor="start", spacing=None):
    ls = f' letter-spacing="{spacing}"' if spacing else ""
    return (f'<text x="{x:.1f}" y="{y:.1f}" font-family="{FONT}" font-size="{size}" font-weight="{weight}" '
            f'fill="{fill}" text-anchor="{anchor}"{ls}>{esc(s)}</text>')


def r(x, y, w, h, fill, rx=0, stroke=None, sw=1, dash=None):
    st = f' stroke="{stroke}" stroke-width="{sw}"' if stroke else ""
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<rect x="{x:.1f}" y="{y:.1f}" width="{max(w, 0):.1f}" height="{max(h, 0):.1f}" rx="{rx}" fill="{fill}"{st}{da}/>'


def line(x1, y1, x2, y2, stroke=HAIR, sw=1, dash=None):
    da = f' stroke-dasharray="{dash}"' if dash else ""
    return f'<line x1="{x1:.1f}" y1="{y1:.1f}" x2="{x2:.1f}" y2="{y2:.1f}" stroke="{stroke}" stroke-width="{sw}"{da}/>'


HATCH = ('<defs><pattern id="hatch" width="8" height="8" patternUnits="userSpaceOnUse" patternTransform="rotate(45)">'
         f'<rect width="8" height="8" fill="{QUIET}"/><line x1="0" y1="0" x2="0" y2="8" stroke="{MUTED}" stroke-width="3"/>'
         '</pattern></defs>')


def frame(h, title, desc, eyebrow, heading, sub, body, source, toggles=None):
    import json as _json
    tg = (f' data-toggles="{html.escape(_json.dumps(toggles, ensure_ascii=False), quote=True)}"' if toggles else "")
    return "\n".join([
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1200 {h}" width="1200" height="{h}" role="img" aria-labelledby="t d"{tg}>',
        MARK,
        f'<title id="t">{esc(title)}</title>',
        f'<desc id="d">{esc(desc)}</desc>',
        HATCH,
        r(0, 0, 1200, h, SHELL),
        t(48, 46, eyebrow, 12, 600, SLATE, spacing=2.4),
        t(48, 86, heading, 31, 700, INK),
        t(48, 114, sub, 14.5, 400, SLATE),
        *body,
        t(48, h - 22, source, 11, 400, MUTED),
        "</svg>", ""])


def hit(x, y, w, h, tip):
    """Une zone de survol invisible : la fiche affiche « tip » (assets/charts.js)."""
    return (f'<rect class="hit" x="{x:.1f}" y="{y:.1f}" width="{max(w, 8):.1f}" height="{max(h, 8):.1f}" '
            f'fill="#000" fill-opacity="0" pointer-events="all" tabindex="0" '
            f'data-tip="{html.escape(tip, quote=True)}"/>')


def group(key, items):
    """Un groupe que les bascules du graphique montrent ou cachent."""
    return [f'<g data-series="{key}">', *items, "</g>"]


def swatch(x, y, fill):
    return r(x, y - 10, 12, 12, fill, 3)


