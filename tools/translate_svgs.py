def english_number(t: str) -> str:
    t = re.sub(r"(\d),(\d)", r"\1.\2", t)
    t = re.sub(r"(\d) (\d{3})", r"\1,\2", t)
    return t


def translate(name: str, s: str) -> tuple[str, list[str]]:
    table = T[name]
    missing = []

    def node(m):
        raw = m.group(1)
        txt = html.unescape(raw)
        if not txt.strip():
            return m.group(0)
        if not re.search(r"[A-Za-zÀ-ÿ]", txt):
            return ">" + html.escape(english_number(txt), quote=False) + "<"
        if txt in table:
            return ">" + html.escape(table[txt], quote=False) + "<"
        if txt in SAME:
            return m.group(0)
        missing.append(txt)
        return m.group(0)

    out = re.sub(r">([^<>]+)<", node, s)
    return out, missing


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    failed = False
    for src in sorted(SRC.glob("*.svg")):
        out, missing = translate(src.name, src.read_text(encoding="utf-8"))
        if missing:
            failed = True
            print(f"{src.name}: non traduit →", *missing, sep="\n  ")
            continue
        (OUT / src.name).write_text(out, encoding="utf-8")
        print(f"{src.name:28} ok")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
