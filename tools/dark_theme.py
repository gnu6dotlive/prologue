#!/usr/bin/env python3
"""Le thème sombre, depuis une seule table de couleurs.

Le site suit le réglage clair / sombre du système ; un bouton à côté de FR · EN
(assets/theme.js) permet aussi de choisir clair ou sombre, retenu par le navigateur.
Les couleurs sombres sont les rôles sombres de gnosix_DS (gnu6.css,
[data-g6-mode="dark"]) : aucune teinte inventée. Les deux séries des graphiques
(orange #C95400, bleu #4169E1) restent les mêmes, validées sur fond sombre ; les
textes de couleur passent à leur ton 300 pour garder 4,5:1.

Le script :
- écrit le bloc sombre de assets/style.css (entre /* dark:begin */ et /* dark:end */),
  deux fois : une pour le système, une pour le choix fait au bouton ;
- produit la version sombre des schémas dessinés à la main
  (assets/diagrams/dark/ et assets/diagrams/en/dark/) ;
- pose dans les pages un <picture> qui choisit le schéma ou l'animation sombre
  quand le thème l'est, et le script du bouton.

Le PDF reste clair : tout le sombre est réservé à l'écran.
tools/make_gifs.py réutilise darken() pour les animations sombres.

Usage : python3 tools/dark_theme.py   (après translate_svgs.py et make_gifs.py)
"""

from __future__ import annotations

import re
import xml.etree.ElementTree as ET
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DIAGRAMS = ROOT / "assets" / "diagrams"
CHART_MARK = "generated by tools/make_charts.py"
SVG_NS = "http://www.w3.org/2000/svg"

# couleur claire → couleur sombre, pour toute surface, tout trait, toute marque
SURFACE = {
    "#F7F3ED": "#111418",  # fond : canvas anthracite
    "#FAF8F5": "#14181C",  # surface-1 : l207c10
    "#FFFFFF": "#1D2228",  # cartes : surface-2, l250c14
    "#111418": "#F7F3ED",  # encre : shellWhite
    "#667085": "#ADB7C1",  # encre 2 : l775c18
    "#A1A6AD": "#8D99A6",  # encre 3 : l678c24
    "#D7DADF": "#323A40",  # filet fort : l343c15
    "#E6E8EB": "#2B3138",  # filet : l310c15
    "#FFE5D2": "#1A1F24",  # teintes 100 : l236c12, la sélection discrète
    "#E8EFE5": "#1A1F24",
    "#E8EDFF": "#1A1F24",
    "#5F7F52": "#8DA982",  # vert : beretGreen/300, le rôle « positif » sombre
    "#455F3D": "#8DA982",
    "#2446A8": "#87A0F4",  # bleu foncé (encre) : royalBlue/300
}
# pour le texte : sa couleur dépend du fond sur lequel il est posé, une fois ce fond
# passé au sombre.
# - fond sombre (le cas courant) : les encres de couleur passent à leur ton 300 ;
TEXT = {
    "#C95400": "#FF8E40",  # signalOrange/300
    "#4169E1": "#87A0F4",
    "#FFFFFF": "#F7F3ED",
}
# - fond devenu clair (un bloc anthracite s'inverse) : l'encre claire prévue pour ce
#   bloc passe à son équivalent sur fond clair ; les autres couleurs gardent leur
#   valeur du thème clair, faite pour un fond clair.
ON_LIGHT = {
    "#FFFFFF": "#111418",
    "#F7F3ED": "#111418",
    "#FAF8F5": "#111418",
    "#A1A6AD": "#667085",
    "#D7DADF": "#667085",
    "#E6E8EB": "#667085",
}

# les variables de la feuille de style, dans leur rôle sombre
VARIABLES = {
    "--ds-shell-white": "#111418",
    "--ds-shell-white-2": "#14181C",
    "--ds-pure-white": "#1D2228",
    "--ds-anthracite": "#F7F3ED",
    "--ds-slate": "#ADB7C1",
    "--ds-muted": "#8D99A6",
    "--ds-hairline": "#323A40",
    "--ds-quiet-divider": "#2B3138",
    "--ds-signal-orange-700": "#FF8E40",
    "--ds-signal-orange-100": "#1D2228",  # fond teinté : surface-2, comme les cartes
    "--ds-beret-green": "#8DA982",
    "--ds-beret-green-700": "#8DA982",
    "--ds-beret-green-100": "#1D2228",
    "--ds-royal-blue-700": "#87A0F4",
    "--ds-royal-blue-100": "#1D2228",
    "--ds-shadow": "0 10px 24px rgba(0, 0, 0, .35)",
}
# composants dont la couleur n'est pas une variable
RULES = [
    (".box.note", "--chip: #87A0F4;"),
    (".btn:hover", "background: #FFFFFF; border-color: #FFFFFF; color: #111418;"),
    (".btn.ghost:hover", "background: #242A31;"),
    (".site-nav a:hover", "background: rgba(247, 243, 237, .05);"),
    ("pre.code", "background: #0B0F14; border: 1px solid var(--ds-quiet-divider);"),
    (".src-card", "box-shadow: 0 14px 32px rgba(0, 0, 0, .5);"),
]


def chart_rules() -> list[tuple[str, str]]:
    """Les graphiques insérés dans la page portent leurs couleurs en attributs : la
    feuille de style les remplace, attribut par attribut. Le texte porte sa couleur
    sombre toute calculée (data-dark-fill, posé par annotate())."""
    out = []
    for light, dark in SURFACE.items():
        out.append((f'svg.chart [fill="{light}" i]', f"fill: {dark};"))
        out.append((f'svg.chart [stroke="{light}" i]', f"stroke: {dark};"))
    inks = sorted(set(SURFACE.values()) | set(TEXT.values()) | set(ON_LIGHT.values())
                  | set(SURFACE) | {"#C95400", "#4169E1", "#FF6A00"})
    for ink in inks:
        out.append((f'svg.chart [data-dark-fill="{ink}"]', f"fill: {ink};"))
    # les anneaux autour des points : couleur du fond de graphique
    out.append(('svg.chart circle[stroke="#FFFFFF" i], svg.chart circle[stroke="#F7F3ED" i]', "stroke: #111418;"))
    return out


def css_block() -> str:
    def body(root: str) -> list[str]:
        lines = [f"  {root} {{", "    color-scheme: dark;"]
        lines += [f"    {k}: {v};" for k, v in VARIABLES.items()]
        lines.append("  }")
        for sel, decl in RULES + chart_rules():
            scoped = ", ".join(f"{root} {s.strip()}" for s in sel.split(", "))
            lines.append(f"  {scoped} {{ {decl} }}")
        return lines

    out = ["/* dark:begin — généré par tools/dark_theme.py, ne pas modifier à la main */",
           "/* Thème sombre : rôles sombres de gnosix_DS. Écran seulement : le PDF reste clair. */",
           "@media screen and (prefers-color-scheme: dark) {"]
    out += body(':root:not([data-theme="light"])')
    out += ["}", "@media screen {"]
    out += body(':root[data-theme="dark"]')
    out += ["}", "/* dark:end */"]
    return "\n".join(out)


def write_css() -> None:
    p = ROOT / "assets" / "style.css"
    s = p.read_text(encoding="utf-8")
    block = css_block()
    if "/* dark:begin" in s:
        s = re.sub(r"/\* dark:begin.*?/\* dark:end \*/", lambda m: block, s, flags=re.S)
    else:
        anchor = "* { box-sizing: border-box; }\n"
        s = s.replace(anchor, block + "\n\n" + anchor, 1)
    p.write_text(s, encoding="utf-8")


# ---------- les SVG ----------

def _tag(el) -> str:
    return el.tag.rsplit("}", 1)[-1]


def _num(v, default=0.0) -> float:
    try:
        return float(re.match(r"-?[\d.]+", v or "").group(0))
    except (AttributeError, ValueError):
        return default


def _translate(el) -> tuple[float, float] | None:
    t = el.get("transform")
    if not t:
        return 0.0, 0.0
    m = re.fullmatch(r"\s*translate\(\s*(-?[\d.]+)[\s,]*(-?[\d.]+)?\s*\)\s*", t)
    if not m:
        return None  # rotation, échelle : on ne suit pas la géométrie
    return float(m.group(1)), float(m.group(2) or 0)


def _light(hex_: str) -> bool:
    h = hex_.lstrip("#")
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    return 0.2126 * r + 0.7152 * g + 0.0722 * b > 0.45


def _dark_fill(c: str) -> str:
    return SURFACE.get(c.upper(), c.upper())


def plan(root) -> dict:
    """Pour chaque texte, sa couleur sombre : celle qui se lit sur le fond qu'il aura
    en sombre (le dernier rectangle ou cercle peint sous lui, sinon le fond du SVG)."""
    shapes: list[tuple[str, tuple]] = []   # (fill sombre, géométrie)
    result = {}

    def under(x, y) -> str:
        for fill, g in reversed(shapes):
            if g[0] == "rect" and g[1] <= x <= g[1] + g[3] and g[2] <= y <= g[2] + g[4]:
                return fill
            if g[0] == "circle" and (x - g[1]) ** 2 + (y - g[2]) ** 2 <= g[3] ** 2:
                return fill
        return SURFACE["#F7F3ED"]

    def walk(el, ox, oy, inherited_fill, tracked):
        if el.get("data-keep") == "1":
            return
        tr = _translate(el)
        if tr is None:
            tracked = False
            tr = (0.0, 0.0)
        ox, oy = ox + tr[0], oy + tr[1]
        tag = _tag(el)
        own = el.get("fill")
        fill = own or inherited_fill
        visible = (own and own != "none" and el.get("fill-opacity") not in ("0", "0.0")
                   and el.get("opacity") not in ("0", "0.0") and own.startswith("#"))
        if tracked and visible and tag == "rect":
            shapes.append((_dark_fill(own), ("rect", ox + _num(el.get("x")), oy + _num(el.get("y")),
                                             _num(el.get("width")), _num(el.get("height")))))
        elif tracked and visible and tag == "circle":
            shapes.append((_dark_fill(own), ("circle", ox + _num(el.get("cx")), oy + _num(el.get("cy")),
                                             _num(el.get("r")))))
        if tag == "text" and fill and fill.startswith("#"):
            size = _num(el.get("font-size"), 12)
            bg = under(ox + _num(el.get("x")), oy + _num(el.get("y")) - size * 0.35) if tracked else SURFACE["#F7F3ED"]
            c = fill.upper()
            dark = ON_LIGHT.get(c, c) if _light(bg) else TEXT.get(c, SURFACE.get(c, c))
            result[el] = dark
            for t in el.iter():
                if t is not el and _tag(t) == "tspan" and t.get("fill"):
                    tc = t.get("fill").upper()
                    result[t] = ON_LIGHT.get(tc, tc) if _light(bg) else TEXT.get(tc, SURFACE.get(tc, tc))
            return
        for child in el:
            walk(child, ox, oy, fill, tracked)

    walk(root, 0.0, 0.0, None, True)
    return result


def _parse(svg: str):
    ET.register_namespace("", SVG_NS)
    ET.register_namespace("xlink", "http://www.w3.org/1999/xlink")
    return ET.fromstring(svg)


def darken(svg: str) -> str:
    """Version sombre d'un SVG, en fichier. Un élément marqué data-keep="1" (un écran
    dessiné, par exemple) garde ses couleurs, avec tout ce qu'il contient ; data-dark-fill
    et data-dark-stroke donnent une couleur qui ne sert qu'en sombre (un bord, par exemple)."""
    root = _parse(svg)
    texts = plan(root)

    def walk(el):
        for attr in ("fill", "stroke"):
            if el.get(f"data-dark-{attr}"):
                el.set(attr, el.get(f"data-dark-{attr}"))
        if el.get("data-keep") == "1":
            for child in el.iter():
                for attr in ("fill", "stroke"):
                    if child is not el and child.get(f"data-dark-{attr}"):
                        child.set(attr, child.get(f"data-dark-{attr}"))
            return
        if el in texts:
            el.set("fill", texts[el])
        elif _tag(el) != "tspan" and el.get("fill", "").upper() in SURFACE:
            el.set("fill", SURFACE[el.get("fill").upper()])
        stroke = el.get("stroke")
        if stroke and stroke.upper() in SURFACE:
            el.set("stroke", SURFACE[stroke.upper()])
        for child in el:
            walk(child)

    walk(root)
    return ET.tostring(root, encoding="unicode") + "\n"


def annotate(svg: str) -> str:
    """Pour un graphique inséré dans la page : chaque texte reçoit data-dark-fill, sa
    couleur sombre ; la feuille de style l'applique quand le thème est sombre."""
    root = _parse(svg)
    for el, dark in plan(root).items():
        el.set("data-dark-fill", dark)
    return ET.tostring(root, encoding="unicode")


def write_svgs() -> int:
    n = 0
    for folder in (DIAGRAMS, DIAGRAMS / "en"):
        out = folder / "dark"
        out.mkdir(exist_ok=True)
        for p in sorted(folder.glob("*.svg")):
            src = p.read_text(encoding="utf-8")
            if CHART_MARK in src:
                continue  # inséré dans la page : la feuille de style s'en charge
            (out / p.name).write_text(darken(src), encoding="utf-8")
            n += 1
    return n


# ---------- les pages ----------

DARK_MEDIA = "screen and (prefers-color-scheme: dark)"


def dark_src(src: str) -> str | None:
    m = re.match(r"((?:\.\./)?assets/(?:diagrams|gif)/(?:en/)?)([\w-]+\.(?:svg|gif))$", src)
    if not m:
        return None
    if not (ROOT / (m.group(1).removeprefix("../") + "dark/" + m.group(2))).exists():
        return None
    return m.group(1) + "dark/" + m.group(2)


def process(page: Path) -> int:
    s = page.read_text(encoding="utf-8")
    prefix = "../" if page.parent.name == "en" else ""
    count = 0

    def wrap(m):
        nonlocal count
        img, src = m.group(0), m.group(1)
        dark = dark_src(src)
        if not dark:
            return img
        count += 1
        return f'<picture><source media="{DARK_MEDIA}" srcset="{dark}">{img}</picture>'

    # déjà posé : on retire avant de reposer
    s = re.sub(r'<picture><source media="[^"]*" srcset="[^"]*">(<img [^>]*>)</picture>', r"\1", s)
    s = re.sub(r'<img (?:class="motion-live" )?src="([^"]+)"[^>]*>', wrap, s)
    tag = f'<script src="{prefix}assets/theme.js"></script>'
    if tag not in s:
        s = s.replace('<link rel="stylesheet"', tag + '\n<link rel="stylesheet"', 1)
    page.write_text(s, encoding="utf-8")
    return count


def main():
    write_css()
    print(f"style.css   bloc sombre ({len(RULES) + len(chart_rules())} règles × 2)")
    print(f"schémas     {write_svgs()} versions sombres")
    for page in sorted(list(ROOT.glob("*.html")) + list((ROOT / "en").glob("*.html"))):
        n = process(page)
        print(f"{page.relative_to(ROOT)!s:20} {n} image{'s' if n > 1 else ''} à deux thèmes")


if __name__ == "__main__":
    main()
